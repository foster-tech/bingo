import { defaultClientConfig, prismaPostgres } from '@prisma/ppg';
import {
  createParishSlug,
  createSessionToken,
  hashPassword,
  hashSessionToken,
  verifyPassword,
} from './auth.js';

let schemaPromise;

function database() {
  if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL não foi definida.');
  }
  return prismaPostgres(defaultClientConfig(process.env.DATABASE_URL));
}

function httpError(status, message) {
  const error = new Error(message);
  error.status = status;
  return error;
}

function normalizeEmail(email) {
  return String(email ?? '').trim().toLowerCase();
}

async function ensureSchema() {
  schemaPromise ??= (async () => {
    const sql = database();
    await sql.sql.exec`
      CREATE TABLE IF NOT EXISTS parishes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        slug TEXT NOT NULL UNIQUE,
        logo_data TEXT,
        banner_data TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `;
    await sql.sql.exec`ALTER TABLE parishes ADD COLUMN IF NOT EXISTS logo_data TEXT`;
    await sql.sql.exec`ALTER TABLE parishes ADD COLUMN IF NOT EXISTS banner_data TEXT`;
    await sql.sql.exec`
      CREATE TABLE IF NOT EXISTS users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `;
    await sql.sql.exec`
      CREATE TABLE IF NOT EXISTS memberships (
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        parish_id INTEGER NOT NULL REFERENCES parishes(id) ON DELETE CASCADE,
        role TEXT NOT NULL DEFAULT 'admin' CHECK (role IN ('admin', 'operator')),
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        PRIMARY KEY (user_id, parish_id)
      )
    `;
    await sql.sql.exec`
      CREATE TABLE IF NOT EXISTS sessions (
        token_hash TEXT PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        expires_at TIMESTAMPTZ NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `;
    await sql.sql.exec`
      CREATE TABLE IF NOT EXISTS games (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        parish_id INTEGER REFERENCES parishes(id) ON DELETE CASCADE,
        win_condition TEXT NOT NULL DEFAULT 'line'
          CHECK (win_condition IN ('line', 'full_card')),
        started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        ended_at TIMESTAMPTZ,
        status TEXT NOT NULL DEFAULT 'active'
          CHECK (status IN ('active', 'finished'))
      )
    `;
    await sql.sql.exec`
      ALTER TABLE games
      ADD COLUMN IF NOT EXISTS parish_id INTEGER REFERENCES parishes(id) ON DELETE CASCADE
    `;
    await sql.sql.exec`
      ALTER TABLE games
      ADD COLUMN IF NOT EXISTS win_condition TEXT NOT NULL DEFAULT 'line'
    `;
    await sql.sql.exec`
      DO $$
      BEGIN
        IF NOT EXISTS (
          SELECT 1
          FROM pg_constraint
          WHERE conname = 'games_win_condition_check'
            AND conrelid = 'games'::regclass
        ) THEN
          ALTER TABLE games
          ADD CONSTRAINT games_win_condition_check
          CHECK (win_condition IN ('line', 'full_card'));
        END IF;
      END $$
    `;
    await sql.sql.exec`
      CREATE TABLE IF NOT EXISTS calls (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        game_id INTEGER NOT NULL REFERENCES games(id) ON DELETE CASCADE,
        number INTEGER NOT NULL CHECK (number BETWEEN 1 AND 75),
        sequence INTEGER NOT NULL,
        called_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        UNIQUE (game_id, number),
        UNIQUE (game_id, sequence)
      )
    `;
    await sql.sql.exec`DROP INDEX IF EXISTS idx_games_one_active`;
    await sql.sql.exec`
      CREATE UNIQUE INDEX IF NOT EXISTS idx_games_one_active_per_parish
      ON games (parish_id)
      WHERE status = 'active' AND parish_id IS NOT NULL
    `;
    await sql.sql.exec`
      CREATE INDEX IF NOT EXISTS idx_games_parish_started
      ON games (parish_id, started_at DESC)
    `;
    await sql.sql.exec`
      CREATE INDEX IF NOT EXISTS idx_calls_game_sequence
      ON calls (game_id, sequence DESC)
    `;
    await sql.sql.exec`
      CREATE INDEX IF NOT EXISTS idx_sessions_user_expiration
      ON sessions (user_id, expires_at)
    `;
  })().catch((error) => {
    schemaPromise = undefined;
    throw error;
  });

  return schemaPromise;
}

function accountPayload(row) {
  return {
    user: { id: row.user_id, name: row.user_name, email: row.email },
    parish: {
      id: row.parish_id,
      name: row.parish_name,
      slug: row.parish_slug,
      logoData: row.logo_data ?? null,
      bannerData: row.banner_data ?? null,
    },
    role: row.role,
  };
}

async function getAccountByUserId(sql, userId) {
  const [row] = await sql.sql`
    SELECT
      u.id AS user_id,
      u.name AS user_name,
      u.email,
      p.id AS parish_id,
      p.name AS parish_name,
      p.slug AS parish_slug,
      p.logo_data,
      p.banner_data,
      m.role
    FROM users u
    JOIN memberships m ON m.user_id = u.id
    JOIN parishes p ON p.id = m.parish_id
    WHERE u.id = ${userId}
    ORDER BY m.created_at ASC
    LIMIT 1
  `.collect();
  return row ? accountPayload(row) : null;
}

export async function registerAccount({ parishName, name, email, password }) {
  await ensureSchema();
  const cleanParishName = String(parishName ?? '').trim();
  const cleanName = String(name ?? '').trim();
  const cleanEmail = normalizeEmail(email);

  if (cleanParishName.length < 3) throw httpError(400, 'Informe o nome da paróquia.');
  if (cleanName.length < 2) throw httpError(400, 'Informe o nome do responsável.');
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(cleanEmail)) throw httpError(400, 'Informe um e-mail válido.');
  if (String(password ?? '').length < 8) throw httpError(400, 'A senha deve ter pelo menos 8 caracteres.');

  const sql = database();
  const passwordHash = await hashPassword(String(password));

  try {
    const userId = await sql.transaction(async (transaction) => {
      const [parish] = await transaction.sql`
        INSERT INTO parishes (name, slug)
        VALUES (${cleanParishName}, ${createParishSlug(cleanParishName)})
        RETURNING id
      `.collect();
      const [user] = await transaction.sql`
        INSERT INTO users (name, email, password_hash)
        VALUES (${cleanName}, ${cleanEmail}, ${passwordHash})
        RETURNING id
      `.collect();
      await transaction.sql.exec`
        INSERT INTO memberships (user_id, parish_id, role)
        VALUES (${user.id}, ${parish.id}, 'admin')
      `;
      await transaction.sql.exec`
        UPDATE games
        SET parish_id = ${parish.id}
        WHERE parish_id IS NULL
      `;
      return user.id;
    });
    return getAccountByUserId(sql, userId);
  } catch (error) {
    if (error.code === '23505') throw httpError(409, 'Já existe uma conta com este e-mail.');
    throw error;
  }
}

export async function authenticateAccount(email, password) {
  await ensureSchema();
  const sql = database();
  const [user] = await sql.sql`
    SELECT id, password_hash
    FROM users
    WHERE email = ${normalizeEmail(email)}
  `.collect();

  if (!user || !(await verifyPassword(String(password ?? ''), user.password_hash))) {
    throw httpError(401, 'E-mail ou senha incorretos.');
  }

  const account = await getAccountByUserId(sql, user.id);
  if (!account) throw httpError(403, 'Esta conta ainda não está vinculada a uma paróquia.');
  return account;
}

export async function createSession(userId) {
  await ensureSchema();
  const sql = database();
  const token = createSessionToken();
  const tokenHash = hashSessionToken(token);
  await sql.sql.exec`DELETE FROM sessions WHERE expires_at <= NOW()`;
  await sql.sql.exec`
    INSERT INTO sessions (token_hash, user_id, expires_at)
    VALUES (${tokenHash}, ${userId}, NOW() + INTERVAL '30 days')
  `;
  return token;
}

export async function getSessionAccount(token, includeBranding = false) {
  if (!token) return null;
  await ensureSchema();
  const sql = database();
  const tokenHash = hashSessionToken(token);
  const [row] = includeBranding
    ? await sql.sql`
        SELECT
          u.id AS user_id,
          u.name AS user_name,
          u.email,
          p.id AS parish_id,
          p.name AS parish_name,
          p.slug AS parish_slug,
          p.logo_data,
          p.banner_data,
          m.role
        FROM sessions s
        JOIN users u ON u.id = s.user_id
        JOIN memberships m ON m.user_id = u.id
        JOIN parishes p ON p.id = m.parish_id
        WHERE s.token_hash = ${tokenHash}
          AND s.expires_at > NOW()
        ORDER BY m.created_at ASC
        LIMIT 1
      `.collect()
    : await sql.sql`
        SELECT
          u.id AS user_id,
          u.name AS user_name,
          u.email,
          p.id AS parish_id,
          p.name AS parish_name,
          p.slug AS parish_slug,
          m.role
        FROM sessions s
        JOIN users u ON u.id = s.user_id
        JOIN memberships m ON m.user_id = u.id
        JOIN parishes p ON p.id = m.parish_id
        WHERE s.token_hash = ${tokenHash}
          AND s.expires_at > NOW()
        ORDER BY m.created_at ASC
        LIMIT 1
      `.collect();
  return row ? accountPayload(row) : null;
}

export async function deleteSession(token) {
  if (!token) return;
  await ensureSchema();
  const sql = database();
  await sql.sql.exec`DELETE FROM sessions WHERE token_hash = ${hashSessionToken(token)}`;
}

export async function updateParishBranding(parishId, kind, dataUrl) {
  await ensureSchema();
  if (!['logo', 'banner'].includes(kind)) throw httpError(400, 'Tipo de imagem inválido.');
  if (!/^data:image\/(?:png|jpe?g|webp);base64,[a-z0-9+/=]+$/i.test(String(dataUrl))) {
    throw httpError(400, 'Envie uma imagem PNG, JPEG ou WebP válida.');
  }
  if (dataUrl.length > 1_500_000) throw httpError(413, 'A imagem ficou muito grande. Escolha um arquivo menor.');

  const sql = database();
  const [parish] = kind === 'logo'
    ? await sql.sql`
        UPDATE parishes SET logo_data = ${dataUrl} WHERE id = ${parishId}
        RETURNING logo_data, banner_data
      `.collect()
    : await sql.sql`
        UPDATE parishes SET banner_data = ${dataUrl} WHERE id = ${parishId}
        RETURNING logo_data, banner_data
      `.collect();

  if (!parish) throw httpError(404, 'Paróquia não encontrada.');
  return { logoData: parish.logo_data ?? null, bannerData: parish.banner_data ?? null };
}

async function withCalls(sql, game) {
  if (!game) return null;
  const calls = await sql.sql`
    SELECT id, game_id, number, sequence, called_at
    FROM calls
    WHERE game_id = ${game.id}
    ORDER BY sequence ASC
  `.collect();
  return { ...game, calls };
}

export async function getCurrentGame(parishId) {
  await ensureSchema();
  const sql = database();
  let [game] = await sql.sql`
    SELECT id, parish_id, win_condition, started_at, ended_at, status
    FROM games
    WHERE parish_id = ${parishId} AND status = 'active'
    ORDER BY id DESC
    LIMIT 1
  `.collect();

  if (!game) {
    [game] = await sql.sql`
      INSERT INTO games (parish_id, status)
      VALUES (${parishId}, 'active')
      ON CONFLICT DO NOTHING
      RETURNING id, parish_id, win_condition, started_at, ended_at, status
    `.collect();
    if (!game) {
      [game] = await sql.sql`
        SELECT id, parish_id, win_condition, started_at, ended_at, status
        FROM games
        WHERE parish_id = ${parishId} AND status = 'active'
        ORDER BY id DESC
        LIMIT 1
      `.collect();
    }
  }

  return withCalls(sql, game);
}

export async function listGames(parishId) {
  await ensureSchema();
  const sql = database();
  return sql.sql`
    SELECT
      g.id,
      g.started_at,
      g.ended_at,
      g.status,
      g.win_condition,
      COUNT(c.id)::INTEGER AS call_count
    FROM games g
    LEFT JOIN calls c ON c.game_id = g.id
    WHERE g.parish_id = ${parishId}
    GROUP BY g.id
    ORDER BY g.id DESC
  `.collect();
}

export async function getGame(parishId, id) {
  await ensureSchema();
  const sql = database();
  const [game] = await sql.sql`
    SELECT id, parish_id, win_condition, started_at, ended_at, status
    FROM games
    WHERE id = ${id} AND parish_id = ${parishId}
  `.collect();
  return withCalls(sql, game);
}

export async function createGame(parishId) {
  await ensureSchema();
  const sql = database();
  const created = await sql.transaction(async (transaction) => {
    await transaction.sql.exec`
      UPDATE games
      SET status = 'finished', ended_at = NOW()
      WHERE parish_id = ${parishId} AND status = 'active'
    `;
    const createdRows = await transaction.sql`
      INSERT INTO games (parish_id, status)
      VALUES (${parishId}, 'active')
      RETURNING id, parish_id, win_condition, started_at, ended_at, status
    `.collect();
    return createdRows[0];
  });
  return withCalls(sql, created);
}

export async function updateGameWinCondition(parishId, gameId, winCondition) {
  await ensureSchema();
  if (!['line', 'full_card'].includes(winCondition)) {
    throw httpError(400, 'Condição de vitória inválida.');
  }

  const sql = database();
  const [game] = await sql.sql`
    UPDATE games
    SET win_condition = ${winCondition}
    WHERE id = ${gameId}
      AND parish_id = ${parishId}
      AND status = 'active'
    RETURNING id, win_condition
  `.collect();

  if (!game) throw httpError(404, 'Jogo ativo não encontrado.');
  return game;
}

export async function addCall(parishId, gameId, number) {
  await ensureSchema();
  const sql = database();
  const [game] = await sql.sql`
    SELECT status FROM games WHERE id = ${gameId} AND parish_id = ${parishId}
  `.collect();

  if (!game) return { status: 404, error: 'Jogo não encontrado.' };
  if (game.status !== 'active') return { status: 409, error: 'Este jogo já foi encerrado.' };
  if (!Number.isInteger(number) || number < 1 || number > 75) {
    return { status: 400, error: 'Digite um número inteiro entre 1 e 75.' };
  }

  try {
    const [call] = await sql.sql`
      INSERT INTO calls (game_id, number, sequence)
      SELECT ${gameId}, ${number}, COALESCE(MAX(sequence), 0) + 1
      FROM calls
      WHERE game_id = ${gameId}
      RETURNING id, game_id, number, sequence, called_at
    `.collect();
    return { call };
  } catch (error) {
    if (error.code === '23505') {
      return { status: 409, error: `O número ${number} já foi chamado neste jogo.` };
    }
    throw error;
  }
}

export async function undoLastCall(parishId, gameId) {
  await ensureSchema();
  const sql = database();
  const [game] = await sql.sql`
    SELECT status FROM games WHERE id = ${gameId} AND parish_id = ${parishId}
  `.collect();

  if (!game) return { status: 404, error: 'Jogo não encontrado.' };
  if (game.status !== 'active') return { status: 409, error: 'Este jogo já foi encerrado.' };

  const [call] = await sql.sql`
    DELETE FROM calls
    WHERE id = (
      SELECT id
      FROM calls
      WHERE game_id = ${gameId}
      ORDER BY sequence DESC
      LIMIT 1
    )
    RETURNING id, game_id, number, sequence, called_at
  `.collect();

  if (!call) return { status: 404, error: 'Ainda não há chamadas para desfazer.' };
  return { call };
}
