import { neon } from '@neondatabase/serverless';

let schemaPromise;

function database() {
  if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL não foi definida.');
  }
  return neon(process.env.DATABASE_URL);
}

async function ensureSchema() {
  schemaPromise ??= (async () => {
    const sql = database();
    await sql`
      CREATE TABLE IF NOT EXISTS games (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        ended_at TIMESTAMPTZ,
        status TEXT NOT NULL DEFAULT 'active'
          CHECK (status IN ('active', 'finished'))
      )
    `;
    await sql`
      CREATE TABLE IF NOT EXISTS calls (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        game_id INTEGER NOT NULL REFERENCES games(id) ON DELETE CASCADE,
        number INTEGER NOT NULL CHECK (number BETWEEN 1 AND 75),
        sequence INTEGER NOT NULL,
        called_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        UNIQUE (game_id, number),
        UNIQUE (game_id, sequence)
      )
    `;
    await sql`
      CREATE UNIQUE INDEX IF NOT EXISTS idx_games_one_active
      ON games (status) WHERE status = 'active'
    `;
    await sql`
      CREATE INDEX IF NOT EXISTS idx_calls_game_sequence
      ON calls (game_id, sequence DESC)
    `;
  })().catch((error) => {
    schemaPromise = undefined;
    throw error;
  });

  return schemaPromise;
}

async function withCalls(sql, game) {
  if (!game) return null;
  const calls = await sql`
    SELECT id, game_id, number, sequence, called_at
    FROM calls
    WHERE game_id = ${game.id}
    ORDER BY sequence ASC
  `;
  return { ...game, calls };
}

export async function getCurrentGame() {
  await ensureSchema();
  const sql = database();
  let [game] = await sql`
    SELECT id, started_at, ended_at, status
    FROM games
    WHERE status = 'active'
    ORDER BY id DESC
    LIMIT 1
  `;

  if (!game) {
    [game] = await sql`
      INSERT INTO games (status)
      VALUES ('active')
      ON CONFLICT DO NOTHING
      RETURNING id, started_at, ended_at, status
    `;
    if (!game) {
      [game] = await sql`
        SELECT id, started_at, ended_at, status
        FROM games
        WHERE status = 'active'
        ORDER BY id DESC
        LIMIT 1
      `;
    }
  }

  return withCalls(sql, game);
}

export async function listGames() {
  await ensureSchema();
  const sql = database();
  return sql`
    SELECT
      g.id,
      g.started_at,
      g.ended_at,
      g.status,
      COUNT(c.id)::INTEGER AS call_count
    FROM games g
    LEFT JOIN calls c ON c.game_id = g.id
    GROUP BY g.id
    ORDER BY g.id DESC
  `;
}

export async function getGame(id) {
  await ensureSchema();
  const sql = database();
  const [game] = await sql`
    SELECT id, started_at, ended_at, status
    FROM games
    WHERE id = ${id}
  `;
  return withCalls(sql, game);
}

export async function createGame() {
  await ensureSchema();
  const sql = database();
  const [, createdRows] = await sql.transaction([
    sql`
      UPDATE games
      SET status = 'finished', ended_at = NOW()
      WHERE status = 'active'
    `,
    sql`
      INSERT INTO games (status)
      VALUES ('active')
      RETURNING id, started_at, ended_at, status
    `,
  ]);
  return withCalls(sql, createdRows[0]);
}

export async function addCall(gameId, number) {
  await ensureSchema();
  const sql = database();
  const [game] = await sql`SELECT status FROM games WHERE id = ${gameId}`;

  if (!game) return { status: 404, error: 'Jogo não encontrado.' };
  if (game.status !== 'active') return { status: 409, error: 'Este jogo já foi encerrado.' };
  if (!Number.isInteger(number) || number < 1 || number > 75) {
    return { status: 400, error: 'Digite um número inteiro entre 1 e 75.' };
  }

  try {
    const [call] = await sql`
      INSERT INTO calls (game_id, number, sequence)
      SELECT ${gameId}, ${number}, COALESCE(MAX(sequence), 0) + 1
      FROM calls
      WHERE game_id = ${gameId}
      RETURNING id, game_id, number, sequence, called_at
    `;
    return { call };
  } catch (error) {
    if (error.code === '23505') {
      return { status: 409, error: `O número ${number} já foi chamado neste jogo.` };
    }
    throw error;
  }
}

export async function undoLastCall(gameId) {
  await ensureSchema();
  const sql = database();
  const [game] = await sql`SELECT status FROM games WHERE id = ${gameId}`;

  if (!game) return { status: 404, error: 'Jogo não encontrado.' };
  if (game.status !== 'active') return { status: 409, error: 'Este jogo já foi encerrado.' };

  const [call] = await sql`
    DELETE FROM calls
    WHERE id = (
      SELECT id
      FROM calls
      WHERE game_id = ${gameId}
      ORDER BY sequence DESC
      LIMIT 1
    )
    RETURNING id, game_id, number, sequence, called_at
  `;

  if (!call) return { status: 404, error: 'Ainda não há chamadas para desfazer.' };
  return { call };
}
